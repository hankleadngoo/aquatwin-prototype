const assert=require('node:assert/strict');
const fs=require('node:fs');
const C=require('./dist/core.js');
const contracts=require('./dist/standards-core.js');
const forecast=require('./dist/forecast-core.js');
const profile=JSON.parse(fs.readFileSync('./dist/architecture-profile.json','utf8'));
const data=JSON.parse(fs.readFileSync('./dist/data.json','utf8'));
const t=contracts.enrich(profile,data,100,C.currentTwin(data,100));
assert.equal(t.attributes.targetId,profile.target.id);
assert.equal(t.features.DO.properties.observed.provenance.inputSnapshotId,data.rows[100].id);
assert.equal(t.features.DO.properties.observed.receivedAt,null);
assert.equal(t.features.DO.properties.observed.phenomenonTime,data.rows[100].ts+'+07:00');
assert(contracts.modelGate(profile,'water-scenario-1.0','research-simulation').allowed);
assert(!contracts.modelGate(profile,'water-scenario-1.0','operational-forecast').allowed);
assert(!contracts.modelGate(profile,'unknown','research-simulation').allowed);
assert.equal(forecast.simulate(data,100,'DO',{purpose:'actuation'}).ok,false);
const wrong=structuredClone(data);wrong.rows[100].site='other';
assert.throws(()=>contracts.enrich(profile,wrong,100,C.currentTwin(wrong,100)),/Unregistered/);
const wrongUnit=structuredClone(data);wrongUnit.params.DO.unit='%';
assert.throws(()=>contracts.enrich(profile,wrongUnit,100,C.currentTwin(wrongUnit,100)),/unit/);
for(const name of ['architecture-ui.js','standards-core.js'])new Function(fs.readFileSync('./dist/'+name,'utf8'));
console.log('PASS: canonical target, state provenance, unknown metadata, identity/unit rejection, research-only model gate and UI syntax.');
